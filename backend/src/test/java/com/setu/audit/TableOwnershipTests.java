package com.setu.audit;

import com.tngtech.archunit.core.domain.JavaAnnotation;
import com.tngtech.archunit.core.domain.JavaClass;
import com.tngtech.archunit.core.domain.JavaClasses;
import com.tngtech.archunit.core.importer.ClassFileImporter;
import com.tngtech.archunit.core.importer.ImportOption;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.simple.JdbcClient;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * One owner per table (Sprint 6 coupling audit, docs/extraction-audit.md). The owner of a table is its schema, and each schema belongs to one
 * module and, in the extraction plan, one service. Three things are enforced:
 * <ol>
 *   <li>every table in the database is in {@code table-owners.txt}: a new table is a deliberate, recorded decision;</li>
 *   <li>every JPA entity maps only a table in its own module's schema: no module's code writes another module's table;</li>
 *   <li>the foreign keys that cross a service boundary are frozen in {@code cross-service-foreign-keys.txt}: these are the constraints that
 *       cannot exist once the services have separate databases and must each be replaced by an application check or an event. A new one is a
 *       decision, and the list can only shrink.</li>
 * </ol>
 * Regenerate the files after a deliberate change with {@code -Dfreeze.update=true}.
 */
@SpringBootTest
class TableOwnershipTests {

    private static final Path OWNERS = Path.of("src/test/resources/table-owners.txt");
    private static final Path FOREIGN_KEYS = Path.of("src/test/resources/cross-service-foreign-keys.txt");

    /** schema -> the extracted service that will own it. Record is folded into Assessment (see the audit); governance is replicated per service. */
    static final Map<String, String> SERVICE_OF_SCHEMA = Map.ofEntries(
        Map.entry("identity", "Identity"),
        Map.entry("institution", "Academic"), Map.entry("catalog", "Academic"), Map.entry("enrollment", "Academic"),
        Map.entry("directory", "Academic"), Map.entry("guardian_access", "Academic"),
        Map.entry("learning", "Learning"),
        Map.entry("assessment", "Assessment"), Map.entry("record", "Assessment"),
        Map.entry("attendance", "Attendance"),
        Map.entry("risk", "StudentSuccess"),
        Map.entry("career", "Career"),
        Map.entry("finance", "Finance"),
        Map.entry("notification", "Notification"),
        Map.entry("governance", "Platform"));

    private static final String SCHEMAS = "'" + String.join("','", SERVICE_OF_SCHEMA.keySet()) + "'";

    @Autowired
    JdbcClient jdbc;

    private static boolean update() {
        return System.getProperty("freeze.update") != null;
    }

    private static Set<String> readFrozen(Path file) throws IOException {
        Set<String> out = new TreeSet<>();
        for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
            if (!line.isBlank() && !line.startsWith("#")) {
                out.add(line.strip());
            }
        }
        return out;
    }

    private static void compare(Set<String> actual, Set<String> frozen, String what, String file) {
        Set<String> added = new TreeSet<>(actual);
        added.removeAll(frozen);
        Set<String> removed = new TreeSet<>(frozen);
        removed.removeAll(actual);
        assertThat(added).as("new " + what + " not in " + file + " (regenerate with -Dfreeze.update=true and update docs/extraction-audit.md)").isEmpty();
        assertThat(removed).as(what + " in " + file + " that no longer exist (regenerate so the list stays honest)").isEmpty();
    }

    @Test
    void everyTableHasExactlyOneRecordedOwner() throws IOException {
        List<String> tables = jdbc.sql("SELECT table_schema || '.' || table_name FROM information_schema.tables WHERE table_type = 'BASE TABLE' AND table_schema IN ("
            + SCHEMAS + ") ORDER BY 1").query(String.class).list();
        Set<String> actual = new TreeSet<>();
        for (String t : tables) {
            actual.add(t + "  " + SERVICE_OF_SCHEMA.get(t.substring(0, t.indexOf('.'))));
        }
        if (update()) {
            List<String> lines = new ArrayList<>();
            lines.add("# schema.table  owning-service. A table's owner is its schema; the service is where that schema goes at extraction. Generated by TableOwnershipTests (-Dfreeze.update=true).");
            lines.addAll(actual);
            Files.writeString(OWNERS, String.join("\n", lines) + "\n", StandardCharsets.UTF_8);
            return;
        }
        compare(actual, readFrozen(OWNERS), "tables", "table-owners.txt");
        assertThat(tables.stream().map(t -> t.substring(0, t.indexOf('.'))).distinct()).as("every schema is owned by a service").allMatch(SERVICE_OF_SCHEMA::containsKey);
    }

    @Test
    void everyEntityMapsOnlyItsOwnModulesSchema() {
        JavaClasses classes = new ClassFileImporter().withImportOption(ImportOption.Predefined.DO_NOT_INCLUDE_TESTS).importPackages("com.setu");
        List<String> wrong = new ArrayList<>();
        int entities = 0;
        for (JavaClass c : classes) {
            if (!c.isAnnotatedWith("jakarta.persistence.Entity")) {
                continue;
            }
            entities++;
            String module = ModuleContractFreezeTests.moduleOf(c);
            String ownSchema = switch (module) {
                case "guardianaccess" -> "guardian_access";
                case "shared" -> "governance";
                default -> module;
            };
            String schema = c.tryGetAnnotationOfType("jakarta.persistence.Table")
                .map(a -> (JavaAnnotation<JavaClass>) a).flatMap(a -> a.get("schema")).map(Object::toString).orElse("(none)");
            if (!schema.equals(ownSchema)) {
                wrong.add(c.getSimpleName() + " in module " + module + " maps schema " + schema);
            }
        }
        assertThat(entities).as("the scan must actually find the entities").isGreaterThan(70);
        assertThat(wrong).as("entities that map a table owned by another module").isEmpty();
    }

    @Test
    void foreignKeysThatCrossAServiceBoundaryAreFrozen() throws IOException {
        Set<String> actual = new TreeSet<>();
        jdbc.sql("""
                SELECT cn.nspname || '.' || c.relname, pn.nspname || '.' || p.relname
                FROM pg_constraint k
                JOIN pg_class c ON c.oid = k.conrelid JOIN pg_namespace cn ON cn.oid = c.relnamespace
                JOIN pg_class p ON p.oid = k.confrelid JOIN pg_namespace pn ON pn.oid = p.relnamespace
                WHERE k.contype = 'f' AND cn.nspname IN (%s) AND pn.nspname IN (%s)
                """.formatted(SCHEMAS, SCHEMAS))
            .query((rs, i) -> new String[] {rs.getString(1), rs.getString(2)}).list().forEach(pair -> {
                String childService = SERVICE_OF_SCHEMA.get(pair[0].substring(0, pair[0].indexOf('.')));
                String parentService = SERVICE_OF_SCHEMA.get(pair[1].substring(0, pair[1].indexOf('.')));
                boolean sameService = childService.equals(parentService);
                // A tenant id and a user id are plain identifiers once services have their own databases: no check needed, no decision to record.
                boolean platformReference = pair[1].equals("institution.colleges") || pair[1].equals("identity.users");
                if (!sameService && !platformReference) {
                    actual.add(childService + " -> " + parentService + "  " + pair[0] + " -> " + pair[1]);
                }
            });
        if (update()) {
            List<String> lines = new ArrayList<>();
            lines.add("# Foreign keys between tables owned by different services (tenant and user references excluded). Each must be replaced by an");
            lines.add("# application-level check or an event before the services get separate databases. Generated by TableOwnershipTests (-Dfreeze.update=true).");
            lines.addAll(actual);
            Files.writeString(FOREIGN_KEYS, String.join("\n", lines) + "\n", StandardCharsets.UTF_8);
            return;
        }
        compare(actual, readFrozen(FOREIGN_KEYS), "cross-service foreign keys", "cross-service-foreign-keys.txt");
    }
}
